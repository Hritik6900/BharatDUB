#!/usr/bin/env python3
"""Regenerate the generated blocks of the Bharat Dub handbook.

Blocks are the text between `<!-- generated:start NAME -->` and `<!-- generated:end NAME -->`.
Only that text is ever rewritten. Python 3 standard library only.

    python scripts/docs/gen_docs.py           # rewrite stale blocks
    python scripts/docs/gen_docs.py --check   # write nothing; exit 1 if any block is stale

Blocks:
    commits                 docs/handbook/history/COMMITS.md
    adr-index               docs/handbook/adr/README.md
    exp-index               docs/handbook/experiments/README.md
    results-live-sessions   docs/handbook/RESULTS.md   (from logs/sessions/index.csv)
    results-studio-jobs     docs/handbook/RESULTS.md   (from logs/jobs/index.csv)
    results-eval            docs/handbook/RESULTS.md   (from backend/eval/results.csv)
"""
from __future__ import annotations

import argparse
import csv
import re
import statistics
import subprocess
import sys
from collections import OrderedDict
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

GEN_LINE = "Generated by scripts/docs/gen_docs.py; do not edit by hand."
DASH = "—"
SUBJECT_MAX = 140
AREA_ORDER = ["backend", "web", "gpu", "docs", "eval", "infra", "logs", "scripts"]
ADR_RE = re.compile(r"ADR-(\d{4})")
EXP_RE = re.compile(r"EXP-(\d{3})")

COMMITS_SKELETON = """# Commit history

Every commit reachable from the local branches and tags, newest first. The table is rebuilt by
`scripts/docs/gen_docs.py` (or `scripts/docs/gen-docs.ps1`); do not edit it by hand.

Notes (hand-written, kept by the generator):

- Remote branches are not read, so the table does not depend on when the repository was last fetched.
- The work of 13-15 Nov 2026 exists twice in this repository: the history of `main` was rewritten once, and the
  older copies (same content and dates, different hashes) are kept only under the rewrite's backup ref. They show
  up in `git log --all` (which is why that count is higher than the total here) but not in this table.
- Area is worked out from the paths a commit changed; +/- counts lines (binary files count as 0). For the merge
  commit the counts are against its first parent.

<!-- generated:start commits -->
<!-- generated:end commits -->
"""


# ---------------------------------------------------------------- helpers

def git(root: Path | None, *args: str) -> str:
    cmd = ["git"]
    if root is not None:
        cmd += ["-C", str(root)]
    cmd += list(args)
    res = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if res.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {res.stderr.strip()}")
    return res.stdout


def repo_root() -> Path:
    here = Path(__file__).resolve().parent
    out = subprocess.run(["git", "-C", str(here), "rev-parse", "--show-toplevel"],
                         capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit("gen_docs: not inside a git repository")
    return Path(out.stdout.strip())


def cell(text: str) -> str:
    return text.replace("\r", " ").replace("\n", " ").replace("|", "\\|").strip()


def half_up(x: float, places: int) -> str:
    q = Decimal(1).scaleb(-places)
    return str(Decimal(str(x)).quantize(q, rounding=ROUND_HALF_UP))


def to_float(v: str | None) -> float | None:
    if v is None:
        return None
    v = v.strip()
    if not v:
        return None
    try:
        return float(v)
    except ValueError:
        return None


def median_or_none(values: list[float]) -> float | None:
    return statistics.median(values) if values else None


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(r) + " |")
    return "\n".join(lines)


def block_text(*parts: str) -> str:
    return "\n\n".join([GEN_LINE, *[p for p in parts if p]])


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


# ---------------------------------------------------------------- commits

def area_of(path: str) -> str:
    p = path.replace("\\", "/")
    if p.startswith("backend/eval/") or p == "backend/eval":
        return "eval"
    if p.startswith("backend/"):
        return "backend"
    if p.startswith("web/"):
        return "web"
    if p.startswith("gpu_engine"):
        return "gpu"
    if p.startswith("docs/") or ("/" not in p and p.lower().endswith(".md")):
        return "docs"
    if p.startswith("logs/"):
        return "logs"
    if p.startswith("scripts/"):
        return "scripts"
    return "infra"


def resolve_rename(path: str) -> str:
    """numstat shows renames as 'a => b' or 'dir/{a => b}/x'; return the new path."""
    m = re.match(r"^(.*)\{(.*) => (.*)\}(.*)$", path)
    if m:
        return (m.group(1) + m.group(3) + m.group(4)).replace("//", "/")
    if " => " in path:
        return path.split(" => ", 1)[1]
    return path


def local_refs(root: Path) -> dict[str, list[str]]:
    out = git(root, "for-each-ref", "refs/heads", "refs/tags",
              "--format=%(objectname)%09%(*objectname)%09%(refname)")
    refs: dict[str, list[str]] = {}
    for line in out.splitlines():
        if not line.strip():
            continue
        obj, peeled, name = line.split("\t")
        target = peeled or obj
        if name.startswith("refs/tags/"):
            label = "tag: " + name[len("refs/tags/"):]
        else:
            label = name[len("refs/heads/"):]
        refs.setdefault(target, []).append(label)
    for k in refs:
        refs[k].sort(key=lambda s: (s.startswith("tag: "), s))
    return refs


def id_links(text: str, root: Path) -> str:
    out: list[str] = []
    seen: set[str] = set()
    hb = root / "docs" / "handbook"
    for m in ADR_RE.finditer(text):
        ident = f"ADR-{m.group(1)}"
        if ident in seen:
            continue
        seen.add(ident)
        files = sorted((hb / "adr").glob(f"{m.group(1)}-*.md"))
        out.append(f"[{ident}](../adr/{files[0].name})" if files else ident)
    for m in EXP_RE.finditer(text):
        ident = f"EXP-{m.group(1)}"
        if ident in seen:
            continue
        seen.add(ident)
        files = sorted((hb / "experiments").glob(f"{ident}-*.md"))
        out.append(f"[{ident}](../experiments/{files[0].name})" if files else ident)
    return ", ".join(out)


def build_commits(root: Path) -> str:
    rs, us = "\x1e", "\x1f"
    fmt = f"{rs}%H{us}%h{us}%ad{us}%an{us}%s{us}%B{us}"
    out = git(root, "log", "--branches", "--tags", "--date=short", "--numstat",
              "--diff-merges=first-parent", f"--format={fmt}")
    refs = local_refs(root)
    commits: "OrderedDict[str, dict]" = OrderedDict()
    for chunk in out.split(rs):
        if not chunk.strip():
            continue
        parts = chunk.split(us)
        if len(parts) < 7:
            continue
        full, short, date, author, subject, body, stat = parts[:7]
        if full in commits:
            continue
        added = deleted = 0
        areas: set[str] = set()
        for line in stat.splitlines():
            cols = line.split("\t")
            if len(cols) != 3:
                continue
            a, d, path = cols
            added += int(a) if a.isdigit() else 0
            deleted += int(d) if d.isdigit() else 0
            areas.add(area_of(resolve_rename(path)))
        commits[full] = {
            "short": short, "date": date, "author": author, "subject": subject,
            "body": body, "added": added, "deleted": deleted, "areas": areas,
        }
    rows = []
    for full, c in commits.items():
        subj = c["subject"]
        if len(subj) > SUBJECT_MAX:
            subj = subj[: SUBJECT_MAX - 3].rstrip() + "..."
        rows.append([
            c["date"],
            f"`{c['short']}`",
            cell(", ".join(refs.get(full, []))),
            cell(c["author"]),
            cell(subj),
            ", ".join(a for a in AREA_ORDER if a in c["areas"]),
            f"+{c['added']}/-{c['deleted']}",
            id_links(c["subject"] + "\n" + c["body"], root),
        ])
    dates = sorted(c["date"] for c in commits.values())
    note = (f"{len(commits)} commits, {dates[0]} to {dates[-1]}." if dates else "No commits found.")
    header = ["Date", "Hash", "Refs", "Author", "Subject", "Area", "+/-", "Refs ADR/EXP"]
    return block_text(note, table(header, rows))


# ---------------------------------------------------------------- indexes

def parse_fields(path: Path) -> dict[str, str]:
    text = read_text(path)
    fields: dict[str, str] = {}
    lines = text.split("\n")
    fields["_first"] = lines[0].strip() if lines else ""
    for line in lines[:60]:
        m = re.match(r"^\s*-\s*\*\*(Status|Date|Decision):\*\*\s*(.*?)\s*$", line)
        if m and m.group(1) not in fields:
            fields[m.group(1)] = m.group(2)
    return fields


def build_adr_index(root: Path) -> str:
    adr_dir = root / "docs" / "handbook" / "adr"
    rows = []
    for f in sorted(adr_dir.glob("[0-9][0-9][0-9][0-9]-*.md")):
        fl = parse_fields(f)
        m = re.match(r"^#\s*ADR-(\d{4}):\s*(.*)$", fl["_first"])
        ident = f"ADR-{m.group(1)}" if m else f"ADR-{f.name[:4]}"
        title = m.group(2) if m else fl["_first"].lstrip("# ")
        rows.append([f"[{ident}]({f.name})", cell(title),
                     cell(fl.get("Status", DASH)) or DASH, cell(fl.get("Date", DASH)) or DASH])
    return block_text(f"{len(rows)} records.", table(["ADR", "Title", "Status", "Date"], rows))


def build_exp_index(root: Path) -> str:
    exp_dir = root / "docs" / "handbook" / "experiments"
    rows = []
    for f in sorted(exp_dir.glob("EXP-[0-9][0-9][0-9]-*.md")):
        fl = parse_fields(f)
        m = re.match(r"^#\s*EXP-(\d{3}):\s*(.*)$", fl["_first"])
        ident = f"EXP-{m.group(1)}" if m else f.name[:7]
        title = m.group(2) if m else fl["_first"].lstrip("# ")
        decision = fl.get("Decision", DASH)
        # Link ADR ids in the decision to their files (relative to experiments/).
        def link(mm: re.Match) -> str:
            files = sorted((root / "docs" / "handbook" / "adr").glob(f"{mm.group(1)}-*.md"))
            return f"[{mm.group(0)}](../adr/{files[0].name})" if files else mm.group(0)
        decision = ADR_RE.sub(link, cell(decision)) if decision else DASH
        rows.append([f"[{ident}]({f.name})", cell(title), cell(fl.get("Date", DASH)) or DASH,
                     cell(fl.get("Status", DASH)) or DASH, decision or DASH])
    return block_text(f"{len(rows)} experiments.",
                      table(["EXP", "Title", "Date", "Status", "Decision"], rows))


# ---------------------------------------------------------------- results

def read_csv(path: Path) -> list[dict[str, str]] | None:
    if not path.exists():
        print(f"warning: {path} missing; block skipped")
        return None
    with path.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def build_live(root: Path) -> str | None:
    rows = read_csv(root / "logs" / "sessions" / "index.csv")
    if rows is None:
        return None
    groups: dict[tuple[str, str], list[dict[str, str]]] = {}
    for r in rows:
        groups.setdefault((r.get("version", ""), r.get("date", "")), []).append(r)
    out = []
    for (version, date) in sorted(groups, key=lambda k: (k[1], k[0])):
        g = groups[(version, date)]
        sessions = len({r.get("session", "") for r in g})
        phrases = sum(int(to_float(r.get("spoken")) or 0) for r in g)
        fa = median_or_none([v for v in (to_float(r.get("first_audio_p50_ms")) for r in g) if v is not None])
        w1 = median_or_none([v for v in (to_float(r.get("within_1s_pct")) for r in g) if v is not None])
        out.append([version, date, str(sessions), str(len(g)), str(phrases),
                    half_up(fa, 0) if fa is not None else DASH,
                    half_up(w1, 1) if w1 is not None else DASH])
    header = ["Version", "Date", "Sessions", "Session-languages", "Phrases",
              "First audio p50 (median of rows, ms)", "Within 1 s (median of rows, %)"]
    return block_text(table(header, out))


def build_jobs(root: Path) -> str | None:
    rows = read_csv(root / "logs" / "jobs" / "index.csv")
    if rows is None:
        return None
    groups: dict[tuple[str, str], list[dict[str, str]]] = {}
    for r in rows:
        groups.setdefault((r.get("version", ""), r.get("date", "")), []).append(r)
    out = []
    for (version, date) in sorted(groups, key=lambda k: (k[1], k[0])):
        g = groups[(version, date)]
        tot = median_or_none([v for v in (to_float(r.get("total_s")) for r in g) if v is not None])
        out.append([version, date, str(len(g)), half_up(tot, 1) if tot is not None else DASH])
    return block_text(table(["Version", "Date", "Jobs", "Median total (s)"], out))


def build_eval(root: Path) -> str | None:
    rows = read_csv(root / "backend" / "eval" / "results.csv")
    if rows is None:
        return None
    out = []
    for r in rows:
        val = (r.get("value") or "").strip()
        out.append([cell(r.get("area") or ""), cell(r.get("metric") or ""), cell(val) if val else DASH,
                     cell(r.get("unit") or ""), cell(r.get("n") or ""), cell(r.get("note") or "")])
    return block_text(table(["Area", "Metric", "Value", "Unit", "n", "Note"], out))


# ---------------------------------------------------------------- block replacement

def replace_block(text: str, name: str, content: str) -> str | None:
    start = f"<!-- generated:start {name} -->"
    end = f"<!-- generated:end {name} -->"
    i = text.find(start)
    j = text.find(end, i + len(start)) if i >= 0 else -1
    if i < 0 or j < 0:
        return None
    return text[: i + len(start)] + "\n" + content.rstrip("\n") + "\n" + text[j:]


COMMITS_REL = "docs/handbook/history/COMMITS.md"


def commits_only_lag(root: Path, text: str) -> bool:
    """True when every commit missing from the block touched COMMITS.md itself and none is extra."""
    m = re.search(r"<!-- generated:start commits -->(.*?)<!-- generated:end commits -->", text, re.S)
    if not m:
        return False
    listed = set(re.findall(r"^\| [0-9-]+ \| `([0-9a-f]+)` \|", m.group(1), re.M))
    out = git(root, "log", "--branches", "--tags", "--format=%x1e%h", "--name-only")
    actual: dict[str, set[str]] = {}
    for chunk in out.split("\x1e"):
        lines = [ln.strip() for ln in chunk.splitlines() if ln.strip()]
        if lines:
            actual.setdefault(lines[0], set()).update(lines[1:])
    if listed - set(actual):
        return False
    missing = set(actual) - listed
    return bool(missing) and all(COMMITS_REL in actual[h] for h in missing)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if any block is stale")
    args = ap.parse_args()

    root = repo_root()
    hb = root / "docs" / "handbook"
    commits_md = hb / "history" / "COMMITS.md"

    plan: list[tuple[Path, str, object]] = [
        (commits_md, "commits", build_commits),
        (hb / "adr" / "README.md", "adr-index", build_adr_index),
        (hb / "experiments" / "README.md", "exp-index", build_exp_index),
        (hb / "RESULTS.md", "results-live-sessions", build_live),
        (hb / "RESULTS.md", "results-studio-jobs", build_jobs),
        (hb / "RESULTS.md", "results-eval", build_eval),
    ]

    texts: dict[Path, str] = {}
    originals: dict[Path, str | None] = {}
    stale: list[str] = []
    unchanged: list[str] = []
    skipped: list[str] = []

    for path, name, builder in plan:
        rel = path.relative_to(root).as_posix()
        if path not in texts:
            if path.exists():
                texts[path] = read_text(path)
                originals[path] = texts[path]
            elif path == commits_md:
                texts[path] = COMMITS_SKELETON
                originals[path] = None
            else:
                print(f"warning: {rel} missing; block '{name}' skipped")
                skipped.append(f"{rel}#{name}")
                continue
        try:
            content = builder(root)  # type: ignore[operator]
        except Exception as exc:  # keep going on one bad source
            print(f"warning: block '{name}' not built: {exc}")
            skipped.append(f"{rel}#{name}")
            continue
        if content is None:
            skipped.append(f"{rel}#{name}")
            continue
        new = replace_block(texts[path], name, content)
        if new is None:
            print(f"warning: markers for '{name}' not found in {rel}; skipped")
            skipped.append(f"{rel}#{name}")
            continue
        if new != texts[path] and name == "commits" and args.check and commits_only_lag(root, texts[path]):
            # The block can never list the commit that updates it: commits that only lag behind because
            # they themselves touched COMMITS.md (and the moved branch label) do not count as stale.
            unchanged.append(f"{rel}#{name}")
        elif new != texts[path]:
            stale.append(f"{rel}#{name}")
            texts[path] = new
        else:
            unchanged.append(f"{rel}#{name}")

    to_write = [p for p, t in texts.items() if originals.get(p) != t]
    for p in texts:
        if originals.get(p) is None and p not in to_write:
            to_write.append(p)

    if args.check:
        for s in stale:
            print(f"STALE {s}")
        for p in to_write:
            if originals.get(p) is None:
                print(f"MISSING {p.relative_to(root).as_posix()}")
        print(f"check: {len(stale)} stale, {len(unchanged)} up to date, {len(skipped)} skipped")
        return 1 if stale or any(originals.get(p) is None for p in to_write) else 0

    for p in to_write:
        p.parent.mkdir(parents=True, exist_ok=True)
        with p.open("w", encoding="utf-8", newline="\n") as fh:
            fh.write(texts[p])
    for s in stale:
        print(f"updated {s}")
    for s in unchanged:
        print(f"unchanged {s}")
    print(f"gen_docs: {len(stale)} block(s) updated, {len(to_write)} file(s) written, "
          f"{len(skipped)} skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
